import { readFile, readdir } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import {
  findSecretLikeKeys,
  normalizeProjectSpec,
  type ResolvedProjectSpec,
} from "@/lib/spec/schema";
import { toProjectYaml } from "@/lib/spec/yaml";
import {
  assertRenderable,
  resolveProjectPlan,
  slugify,
  TEMPLATE_ID,
  TEMPLATE_VERSION,
  type ProjectPlan,
} from "@/lib/spec/plan";

const BINARY_EXTENSIONS = new Set([
  ".png",
  ".jpg",
  ".jpeg",
  ".gif",
  ".webp",
  ".ico",
  ".woff",
  ".woff2",
  ".ttf",
  ".otf",
]);

const GENERATED_AT = "2020-01-01T00:00:00.000Z";
const LOCK_SCHEMA_VERSION = 1;

export type TemplateLock = {
  schemaVersion: number;
  template: { id: string; version: string; structure: string };
  specHash: string;
  files: { path: string; sha256: string }[];
  checksum: string;
};

export type RenderedScaffold = {
  slug: string;
  files: Record<string, string>;
  lock: TemplateLock;
  plan: ProjectPlan;
};

function sha256(value: string): string {
  return createHash("sha256").update(value).digest("hex");
}

function toPosix(path: string): string {
  return path.split(sep).join("/");
}

function isIncluded(relPath: string, spec: ResolvedProjectSpec): boolean {
  if (relPath.endsWith(".DS_Store")) return false;
  if (relPath.startsWith("infra/convex/") && spec.deploy.convex !== "self-hosted") {
    return false;
  }
  if (relPath.startsWith("src/features/blog/") && !spec.features.blog) return false;
  if (relPath.startsWith("src/features/email/") && spec.features.email === "none") {
    return false;
  }
  if (relPath.startsWith("src/features/analytics/") && spec.features.analytics === "none") {
    return false;
  }
  return true;
}

async function walk(root: string, current = root): Promise<string[]> {
  const entries = await readdir(current, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const full = join(current, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(root, full)));
    } else if (entry.isFile()) {
      files.push(toPosix(relative(root, full)));
    }
  }
  return files;
}

function substitutions(spec: ResolvedProjectSpec, slug: string): Record<string, string> {
  return {
    "{{project.name}}": spec.name,
    "{{project.slug}}": slug,
    "{{project.description}}": spec.description,
    "{{project.domain}}": spec.domain ?? "localhost:3000",
    "{{spec.structure}}": spec.structure,
    "{{spec.frontend}}": spec.frontend,
    "{{spec.audience}}": spec.audience,
    "{{spec.auth}}": spec.auth,
    "{{spec.payments}}": spec.payments,
    "{{spec.backend.advanced}}": spec.backend.advanced,
    "{{spec.backend.database}}": spec.backend.database,
    "{{spec.deploy.provider}}": spec.deploy.provider,
    "{{spec.deploy.convex}}": spec.deploy.convex,
    "{{spec.deploy.dns}}": spec.deploy.dns,
    "{{spec.deploy.registrar}}": spec.deploy.registrar,
    "{{spec.features.demo}}": String(spec.features.demo),
    "{{spec.features.blog}}": String(spec.features.blog),
    "{{spec.features.email}}": spec.features.email,
    "{{spec.features.analytics}}": spec.features.analytics,
    "{{spec.templateVersion}}": spec.templateVersion,
    "{{generatedBy}}": `new-saas ${TEMPLATE_ID} ${TEMPLATE_VERSION}`,
    "{{generatedAt}}": GENERATED_AT,
  };
}

function substitute(content: string, values: Record<string, string>, path: string): string {
  let output = content;
  for (const [token, value] of Object.entries(values)) {
    output = output.split(token).join(value);
  }
  const leftover = output.match(/\{\{[^}]+\}\}/g);
  if (leftover) {
    throw new Error(`Unresolved template token(s) in ${path}: ${leftover.join(", ")}`);
  }
  return output;
}

function buildEnvExample(plan: ProjectPlan): string {
  const lines = [
    "# Generated by new-saas. Copy to .env.local and fill values there.",
    "# Never commit filled values. Secret values are intentionally blank.",
    "",
  ];
  for (const envVar of plan.envVars) {
    lines.push(`# ${envVar.description}`);
    lines.push(`${envVar.name}=`);
    lines.push("");
  }
  return lines.join("\n");
}

function buildSetupDoc(plan: ProjectPlan, spec: ResolvedProjectSpec): string {
  const envLines = plan.envVars
    .map(
      (envVar) =>
        `| \`${envVar.name}\` | ${envVar.visibility} | ${envVar.required ? "yes" : "no"} | ${envVar.description} |`,
    )
    .join("\n");

  const infraLines = plan.infra
    .map(
      (step) =>
        `1. **${step.title}** (${step.provider}, stubbed)\n   ${step.description}`,
    )
    .join("\n");

  return `# ${spec.name} — setup

Generated deterministically from \`project.yaml\` by new-saas ${TEMPLATE_ID} ${TEMPLATE_VERSION}.

## 1. Open the app without integrations

\`\`\`bash
cp .env.example .env.local
npm install
npm run dev
\`\`\`

With an empty \`.env.local\`, the app runs in demo mode: demo auth, fixtures, and no checkout.
Demo mode is rejected in production.

## 2. Wire Convex

\`\`\`bash
npx convex dev
\`\`\`

Copy the deployment URL into \`NEXT_PUBLIC_CONVEX_URL\`, then set:

\`\`\`bash
NEXT_PUBLIC_AUTH_MODE=real
NEXT_PUBLIC_DATA_MODE=convex
\`\`\`

Auth is **${plan.auth.provider}**. ${plan.auth.reason}

## 3. Environment variables

| Variable | Visibility | Required | Purpose |
| --- | --- | --- | --- |
${envLines}

Secrets stay in the deployment platform. The spec never contains secret values.

## 4. Infrastructure (stubbed in v0)

Plan only; no provider API is called by this build.

${infraLines}

## 5. Verify

\`\`\`bash
npm run typecheck
npm run test
npm run build
\`\`\`

All three must pass before handoff.
`;
}

function buildLock(
  spec: ResolvedProjectSpec,
  files: Record<string, string>,
): TemplateLock {
  const entries = Object.keys(files)
    .sort()
    .map((path) => ({ path, sha256: sha256(files[path]) }));
  const checksum = sha256(
    entries.map((entry) => `${entry.path}\0${entry.sha256}`).join("\0"),
  );

  return {
    schemaVersion: LOCK_SCHEMA_VERSION,
    template: { id: TEMPLATE_ID, version: TEMPLATE_VERSION, structure: spec.structure },
    specHash: sha256(toProjectYaml(spec)),
    files: entries,
    checksum,
  };
}

export async function renderScaffold(input: unknown): Promise<RenderedScaffold> {
  const secretKeys = findSecretLikeKeys(input);
  if (secretKeys.length > 0) {
    throw new Error(
      `Specs must reference env var names, not secrets. Remove: ${secretKeys.join(", ")}`,
    );
  }

  const spec = normalizeProjectSpec(input);
  const plan = resolveProjectPlan(spec);
  assertRenderable(plan);

  const templateRoot = join(process.cwd(), "templates", "v0", "base");
  const values = substitutions(spec, plan.slug);
  const templateFiles = await walk(templateRoot);
  const files: Record<string, string> = {};

  for (const relPath of templateFiles) {
    if (!isIncluded(relPath, spec)) continue;
    const extension = relPath.slice(relPath.lastIndexOf("."));
    if (BINARY_EXTENSIONS.has(extension)) {
      throw new Error(`Template file ${relPath} is binary; v0 templates must be text.`);
    }
    const raw = await readFile(/* turbopackIgnore: true */ join(templateRoot, relPath), "utf8");
    files[relPath] = substitute(raw, values, relPath);
  }

  files["project.yaml"] = toProjectYaml(spec);
  files[".env.example"] = buildEnvExample(plan);
  files["SETUP.md"] = buildSetupDoc(plan, spec);

  const lock = buildLock(spec, files);
  files["template.lock"] = `${JSON.stringify(lock, null, 2)}\n`;

  return { slug: plan.slug, files, lock, plan };
}

export function scaffoldFilename(slug: string): string {
  return `${slug}-${TEMPLATE_ID}.zip`;
}

